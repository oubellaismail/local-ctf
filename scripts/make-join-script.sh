#!/usr/bin/env bash
# make-join-script.sh — write .secrets/join-agent.sh, a self-contained script
# that turns another Ubuntu laptop into a CHALLENGE node.
#
# Copy it to the agent laptop (USB / scp) and run:  sudo bash join-agent.sh
# It contains the cluster join token and registry password: don't share it.

. "$(dirname "$0")/lib.sh"
load_config
# shellcheck source=/dev/null
. "$SECRETS_DIR/registry.env"

TOKEN="$(sudo cat /var/lib/rancher/k3s/server/node-token)"
K3S_VER="$(k3s --version 2>/dev/null | awk 'NR==1 {print $3}')"
CORE_NAME="$(hostname)"
OUT="$SECRETS_DIR/join-agent.sh"

cat > "$OUT" <<EOF
#!/usr/bin/env bash
# Generated by local-ctf make-join-script.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Joins this Ubuntu laptop to the CTF cluster at ${CTF_HOST} as a challenge node.
# Usage: sudo bash join-agent.sh [this-laptop-LAN-IP]
set -euo pipefail
[[ \$EUID -eq 0 ]] || { echo "Run with sudo"; exit 1; }

CORE=${CTF_HOST}
NODE_IP="\${1:-\$(ip -4 route get \$CORE | awk '{for(i=1;i<=NF;i++) if(\$i=="src") print \$(i+1)}')}"
echo "Joining as \$NODE_IP → core \$CORE"

curl -sf --max-time 5 -k https://\$CORE:6443/ping >/dev/null \\
  || { echo "Cannot reach https://\$CORE:6443 — same network? core firewall?"; exit 1; }

# Node names must be unique: a cloned VM keeps the core's hostname
if [[ "\$(hostname)" == "${CORE_NAME}" ]]; then
  echo "This machine is also called '${CORE_NAME}' (cloned VM?). Rename it first:"
  echo "  sudo hostnamectl set-hostname ctf-agent-1"
  exit 1
fi

# Same settings as the core: no swap, and systemd-networkd must not delete
# the pod routes when it restarts
swapoff -a
sed -i '/ swap /s/^[^#]/#&/' /etc/fstab
mkdir -p /etc/systemd/networkd.conf.d
printf '[Network]\nManageForeignRoutes=no\nManageForeignRoutingPolicyRules=no\n' \
  > /etc/systemd/networkd.conf.d/local-ctf.conf

# Keep awake
systemctl mask sleep.target suspend.target hibernate.target hybrid-sleep.target >/dev/null 2>&1 || true
mkdir -p /etc/systemd/logind.conf.d
printf '[Login]\nHandleLidSwitch=ignore\nHandleLidSwitchExternalPower=ignore\nHandleLidSwitchDocked=ignore\n' \\
  > /etc/systemd/logind.conf.d/local-ctf.conf

# Pull challenge images from the core laptop's registry
mkdir -p /etc/rancher/k3s
cat > /etc/rancher/k3s/registries.yaml <<'REG'
mirrors:
  "${REGISTRY}":
    endpoint:
      - "http://${CTF_HOST}:5000"
configs:
  "${CTF_HOST}:5000":
    auth:
      username: ${REGISTRY_USER}
      password: ${REGISTRY_PASSWORD}
REG
chmod 600 /etc/rancher/k3s/registries.yaml

if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  ufw allow 30000:32767/tcp comment 'local-ctf challenges' >/dev/null
  ufw allow 10250/tcp comment 'kubelet' >/dev/null
  ufw allow 8472/udp comment 'flannel' >/dev/null
fi

curl -sfL https://get.k3s.io | \\
  INSTALL_K3S_VERSION="${K3S_VER}" \\
  K3S_URL="https://\$CORE:6443" \\
  K3S_TOKEN="${TOKEN}" \\
  INSTALL_K3S_EXEC="agent --node-ip \$NODE_IP --node-label ctf/role=challenges --kubelet-arg max-pods=250" \\
  sh -

echo ""
echo "Joined. On the core laptop check with: kubectl get nodes -L ctf/role"
EOF
chmod 600 "$OUT"
ok "Wrote $OUT (contains the join token — keep it private)"
